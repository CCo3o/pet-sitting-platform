CREATE TABLE IF NOT EXISTS accounts (id BIGINT PRIMARY KEY, role VARCHAR(16) NOT NULL);
CREATE SEQUENCE IF NOT EXISTS account_id_sequence START WITH 1000;
CREATE TABLE IF NOT EXISTS credentials (
 account_id BIGINT PRIMARY KEY REFERENCES accounts(id), username VARCHAR(32) NOT NULL UNIQUE,
 display_name VARCHAR(40) NOT NULL, password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS login_sessions (
 token_id VARCHAR(36) PRIMARY KEY, account_id BIGINT NOT NULL REFERENCES accounts(id),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS pets (
 id VARCHAR(36) PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES accounts(id),
 name VARCHAR(80) NOT NULL, notes VARCHAR(1000) NOT NULL
);
CREATE TABLE IF NOT EXISTS slots (
 id VARCHAR(36) PRIMARY KEY, sitter_id BIGINT NOT NULL REFERENCES accounts(id),
 starts_at TIMESTAMP WITH TIME ZONE NOT NULL, ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
 price_cents INT NOT NULL CHECK(price_cents > 0), booked BOOLEAN NOT NULL DEFAULT FALSE,
 CHECK(ends_at > starts_at)
);
CREATE TABLE IF NOT EXISTS orders (
 id VARCHAR(36) PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES accounts(id),
 pet_id VARCHAR(36) NOT NULL REFERENCES pets(id), slot_id VARCHAR(36) NOT NULL REFERENCES slots(id),
 status VARCHAR(16) NOT NULL CHECK(status IN ('PENDING','ACCEPTED','COMPLETED','CANCELLED')),
 request_key VARCHAR(100) NOT NULL, price_cents INT NOT NULL,
 UNIQUE(owner_id, request_key)
);
CREATE TABLE IF NOT EXISTS service_records (
 id VARCHAR(36) PRIMARY KEY, order_id VARCHAR(36) NOT NULL REFERENCES orders(id),
 note VARCHAR(2000) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
